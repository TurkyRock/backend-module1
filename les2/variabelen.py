 # Een variabele slaat een waarde op
naam = "Lisa"
leeftijd = 16

print(naam)
print(leeftijd)

# Verschillende datatypes
voornaam = "Ahmed"       # tekst (str)
student_leeftijd = 18    # geheel getal (int)
lengte = 1.82            # kommagetal (float)
is_student = True        # waar of niet waar (bool)

print(voornaam)
print(student_leeftijd)
print(lengte)
print(is_student)

# Rekenen met variabelen
aantal = 5
prijs = 3
totaal = aantal * prijs

print(totaal)

# Een variabele aanpassen
punten = 10
punten = punten + 5
punten += 5

print(punten)

# Tekst combineren
achternaam = "Jansen"
volledige_naam = voornaam + " " + achternaam

print(volledige_naam)
